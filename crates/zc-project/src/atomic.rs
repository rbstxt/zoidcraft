//! Crash-safe atomic file writer (zero `unsafe`).
//!
//! Writes data to a unique sibling temporary file, flushes and calls `sync_all()`,
//! atomically renames over the target path, and removes the temporary file if any
//! step fails or unwinds.

use std::fs::{self, File, OpenOptions};
use std::io::{BufWriter, Write};
use std::path::{Path, PathBuf};

use uuid::Uuid;

use crate::ProjectError;

struct TempFileGuard {
    path: PathBuf,
    armed: bool,
}

impl TempFileGuard {
    fn new(path: PathBuf) -> Self {
        Self { path, armed: true }
    }

    fn disarm(&mut self) {
        self.armed = false;
    }
}

impl Drop for TempFileGuard {
    fn drop(&mut self) {
        if self.armed {
            let _ = fs::remove_file(&self.path);
        }
    }
}

fn create_unique_sibling(target: &Path) -> Result<(File, PathBuf), ProjectError> {
    let parent = match target.parent() {
        Some(dir) if !dir.as_os_str().is_empty() => {
            fs::create_dir_all(dir)?;
            dir
        }
        _ => Path::new("."),
    };

    let base_name = target
        .file_name()
        .and_then(|s| s.to_str())
        .unwrap_or("zcraft");
    let pid = std::process::id();

    for _ in 0..16 {
        let candidate = parent.join(format!(".{base_name}.{pid}.{}.tmp", Uuid::new_v4()));
        match OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&candidate)
        {
            Ok(file) => return Ok((file, candidate)),
            Err(err) if err.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(err) => return Err(ProjectError::Io(err)),
        }
    }

    Err(ProjectError::Io(std::io::Error::new(
        std::io::ErrorKind::AlreadyExists,
        "failed to allocate unique temporary file name",
    )))
}

#[cfg(unix)]
fn sync_parent_dir(target: &Path) {
    let parent = match target.parent() {
        Some(dir) if !dir.as_os_str().is_empty() => dir,
        _ => Path::new("."),
    };
    if let Ok(dir) = File::open(parent) {
        let _ = dir.sync_all();
    }
}

#[cfg(not(unix))]
fn sync_parent_dir(_target: &Path) {}

/// Atomically writes `bytes` to `target` using a unique sibling temporary file
/// followed by `sync_all()` and `fs::rename`.
pub fn write_atomic(target: &Path, bytes: &[u8]) -> Result<(), ProjectError> {
    write_atomic_with(target, |writer| {
        writer.write_all(bytes)?;
        Ok(())
    })
}

/// Atomically streams content generated by `write_fn` to `target`.
///
/// If `write_fn` returns an error, the temporary file is deleted and any existing
/// file at `target` remains untouched.
pub fn write_atomic_with<F>(target: &Path, write_fn: F) -> Result<(), ProjectError>
where
    F: FnOnce(&mut BufWriter<File>) -> Result<(), ProjectError>,
{
    let (file, tmp_path) = create_unique_sibling(target)?;
    let mut guard = TempFileGuard::new(tmp_path.clone());

    let mut writer = BufWriter::new(file);
    write_fn(&mut writer)?;
    writer.flush()?;

    let file = writer.into_inner().map_err(|err| err.into_error())?;
    file.sync_all()?;
    drop(file);

    fs::rename(&tmp_path, target)?;
    guard.disarm();
    sync_parent_dir(target);

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    struct TestDir(PathBuf);

    impl TestDir {
        fn new() -> Self {
            let path = std::env::temp_dir().join(format!("zc-atomic-test-{}", Uuid::new_v4()));
            fs::create_dir_all(&path).expect("create test dir");
            Self(path)
        }
    }

    impl Drop for TestDir {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn atomic_create_and_replace_leaves_no_temp_files() {
        let dir = TestDir::new();
        let target = dir.0.join("project.zcraft");

        write_atomic(&target, b"first version").expect("write v1");
        assert_eq!(fs::read(&target).expect("read v1"), b"first version");

        write_atomic(&target, b"second version").expect("write v2");
        assert_eq!(fs::read(&target).expect("read v2"), b"second version");

        let entries: Vec<_> = fs::read_dir(&dir.0)
            .expect("list dir")
            .map(|e| e.expect("entry").file_name())
            .collect();
        assert_eq!(entries.len(), 1);
    }

    #[test]
    fn failed_atomic_write_preserves_existing_file_and_cleans_temp() {
        let dir = TestDir::new();
        let target = dir.0.join("project.zcraft");
        write_atomic(&target, b"stable").expect("seed file");

        let res = write_atomic_with(&target, |w| {
            w.write_all(b"partial")?;
            Err(ProjectError::UnsupportedFormat("simulated failure".into()))
        });
        assert!(res.is_err());
        assert_eq!(fs::read(&target).expect("read stable"), b"stable");

        let entries: Vec<_> = fs::read_dir(&dir.0)
            .expect("list dir")
            .map(|e| e.expect("entry").file_name())
            .collect();
        assert_eq!(entries.len(), 1);
    }
}
