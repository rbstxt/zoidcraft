#[test]
fn expresstext_30fps_all_five_cases_match_zoidium_matrices_bit_accurately() {
    let root_pos = [4.0, 3.0, 2.0];
    let bases = [[-8.0, 0.0, 0.0], [6.0, 0.0, 0.0]];
    let list = LetterList {
        total: 2,
        order: vec![0, 1],
    };
    let aux = EvalAux::default();
    let frames = [0.0, 13.0, 30.0];

    // Build all 5 property maps matching `expresstext-plus-identity.test.js:9-15`.
    let empty_layers: Vec<EffectorLayer<'_>> = Vec::new();

    let mut plain_props = BTreeMap::new();
    plain_props.insert("plainPosition".into(), EtValue::Vec3([12.0, -4.0, 2.0]));
    plain_props.insert("plainRotation".into(), EtValue::Vec3([0.0, 0.0, 0.3]));
    let plain_layers = vec![EffectorLayer {
        kind: EffectorKind::Plain,
        props: &plain_props,
    }];

    let mut random_props = BTreeMap::new();
    random_props.insert("randomMode".into(), EtValue::Number(2.0));
    random_props.insert("randomAnimationSpeed".into(), EtValue::Number(50.0));
    random_props.insert("randomSeed".into(), EtValue::Number(7.0));
    let random_layers = vec![EffectorLayer {
        kind: EffectorKind::Random,
        props: &random_props,
    }];

    let mut formula_props = BTreeMap::new();
    formula_props.insert(
        "formulaExpression".into(),
        EtValue::Text("60*t + 30*sin(u*360)".into()),
    );
    formula_props.insert("formulaPosition".into(), EtValue::Vec3([1.0, 0.0, 0.0]));
    let formula_layers = vec![EffectorLayer {
        kind: EffectorKind::Formula,
        props: &formula_props,
    }];

    let mut shake_props = BTreeMap::new();
    shake_props.insert("shakePosition".into(), EtValue::Vec3([2.0, 5.0, 1.0]));
    shake_props.insert("shakeFrequency".into(), EtValue::Number(1.25));
    let shake_layers = vec![EffectorLayer {
        kind: EffectorKind::Shake,
        props: &shake_props,
    }];

    let all_cases: [(&str, &[EffectorLayer<'_>]); 5] = [
        ("empty", &empty_layers),
        ("plain", &plain_layers),
        ("random_noise", &random_layers),
        ("formula", &formula_layers),
        ("shake", &shake_layers),
    ];

    for (case_idx, (name, layers)) in all_cases.iter().enumerate() {
        for (frame_idx, &frame) in frames.iter().enumerate() {
            for (letter_idx, &base) in bases.iter().enumerate() {
                let ctrl = evaluate_stack(layers, frame, letter_idx, &list, base, &aux);
                let actual = compose_anchor_world_matrix(root_pos, base, &ctrl);
                let expected = &EXPRESSTEXT_30FPS_GOLDEN[case_idx][frame_idx][letter_idx];
                assert_slice_close(
                    &actual,
                    expected,
                    1e-11,
                    &format!("case={name} frame={frame} letter={letter_idx}"),
                );
            }
        }
    }
}

