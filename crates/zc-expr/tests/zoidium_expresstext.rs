#[test]
fn seed_random_and_methods_match_zoidium_api_js() {
    let cfg = EvalConfig::expressions_plus();

    // Zoidium `plugins/expressions-plus/api.js:249-253`:
    // `n = seed + (timeless ? 0 : frame) * 17.173 + randomIndex++ * 71.137; cm3_random(n)`
    let ctx0 = BasicContext {
        frame: 0.0,
        ..Default::default()
    };
    let ctx30 = BasicContext {
        frame: 30.0,
        ..Default::default()
    };

    let timeless_0 = eval(
        "seedRandom(42, true); [random(), random(), random(10)]",
        &ctx0,
        &cfg,
    )
    .unwrap()
    .as_f64_vec()
    .unwrap();
    let timeless_30 = eval(
        "seedRandom(42, true); [random(), random(), random(10)]",
        &ctx30,
        &cfg,
    )
    .unwrap()
    .as_f64_vec()
    .unwrap();
    assert_eq!(
        timeless_0, timeless_30,
        "timeless seedRandom invariant across frames"
    );
    assert_close(timeless_0[0], cm3_random(42.0), 1e-15, "timeless random #0");
    assert_close(
        timeless_0[1],
        cm3_random(42.0 + 71.137),
        1e-15,
        "timeless random #1",
    );
    assert_close(
        timeless_0[2],
        cm3_random(10.0),
        1e-15,
        "1-arg random(10) keeps CM3 hash",
    );

    let timed_30 = eval("seedRandom(42, false); [random(), random()]", &ctx30, &cfg)
        .unwrap()
        .as_f64_vec()
        .unwrap();
    assert_close(
        timed_30[0],
        cm3_random(42.0 + 30.0 * 17.173),
        1e-15,
        "timed random #0",
    );
    assert_close(
        timed_30[1],
        cm3_random(42.0 + 30.0 * 17.173 + 71.137),
        1e-15,
        "timed random #1",
    );

    // Unseeded 0-arg `random()` falls back to base value with "needs a seed" error
    // (`expressions-plus-engine.test.js:17-23`).
    let ctx_base = BasicContext {
        value: Value::Number(7.0),
        ..Default::default()
    };
    let outcome = eval_with_fallback("random() * 10", &ctx_base, &cfg);
    assert_eq!(outcome.value, Value::Number(7.0));
    let err_msg = outcome.error.expect("expected error").to_string();
    assert!(
        err_msg.contains("needs a seed"),
        "expected 'needs a seed' diagnostic, got: {err_msg}"
    );

    // `methods` namespace access works in both Vanilla CM3 and Expressions+.
    let vanilla_cfg = EvalConfig::vanilla();
    let m_rand = eval("var h = methods.random; h(12)", &ctx0, &vanilla_cfg)
        .unwrap()
        .as_f64()
        .unwrap();
    assert_close(m_rand, cm3_random(12.0), 1e-15, "methods.random(12)");
    let m_lin = eval("methods.linear(10, 20, 0.25)", &ctx0, &vanilla_cfg)
        .unwrap()
        .as_f64()
        .unwrap();
    assert_close(m_lin, 12.5, 1e-15, "methods.linear(10, 20, 0.25)");
}

#[test]
fn ease_in_ease_out_cubic_outin_and_look_at_match_zoidium_golden() {
    let ctx = BasicContext::default();
    let plus = EvalConfig::expressions_plus();
    let vanilla = EvalConfig::vanilla();

    // Zoidium Quadratic `easeIn` (t^2) & `easeOut` (t*(2-t)) across 1-, 3-, and 5-arg overloads.
    for &(t, exp_in, exp_out) in &[
        (0.0, 0.0, 0.0),
        (0.25, 0.0625, 0.4375),
        (0.5, 0.25, 0.75),
        (0.75, 0.5625, 0.9375),
        (1.0, 1.0, 1.0),
    ] {
        assert_close(
            eval(&format!("easeIn({t})"), &ctx, &plus)
                .unwrap()
                .as_f64()
                .unwrap(),
            exp_in,
            1e-15,
            "1-arg easeIn",
        );
        assert_close(
            eval(&format!("easeOut({t})"), &ctx, &plus)
                .unwrap()
                .as_f64()
                .unwrap(),
            exp_out,
            1e-15,
            "1-arg easeOut",
        );
        assert_close(
            eval(&format!("easeIn({t}, 10, 50)"), &ctx, &plus)
                .unwrap()
                .as_f64()
                .unwrap(),
            10.0 + 40.0 * exp_in,
            1e-12,
            "3-arg easeIn",
        );
        assert_close(
            eval(&format!("easeOut({t}, 10, 50)"), &ctx, &plus)
                .unwrap()
                .as_f64()
                .unwrap(),
            10.0 + 40.0 * exp_out,
            1e-12,
            "3-arg easeOut",
        );
        assert_close(
            eval(&format!("easeIn({t}, 0, 1, 100, 200)"), &ctx, &plus)
                .unwrap()
                .as_f64()
                .unwrap(),
            100.0 + 100.0 * exp_in,
            1e-12,
            "5-arg easeIn",
        );
        assert_close(
            eval(&format!("easeOut({t}, 0, 1, 100, 200)"), &ctx, &plus)
                .unwrap()
                .as_f64()
                .unwrap(),
            100.0 + 100.0 * exp_out,
            1e-12,
            "5-arg easeOut",
        );
    }

    // 5-arg vector interpolation (`api.js:4-7`)
    let v_ease = eval("easeIn(0.5, 0, 1, [0, 10], [100, 50])", &ctx, &plus)
        .unwrap()
        .as_f64_vec()
        .unwrap();
    assert_slice_close(&v_ease, &[25.0, 20.0], 1e-12, "5-arg vector easeIn");

    // Legacy vs modern 5-arg `linear` (`expressions-plus-engine.test.js:53-55`):
    // Without extended syntax, extra args keep CM3 3-arg `linear(a, b, t)` (`0.5 + (0 - 0.5)*1 = 0`).
    // With extended syntax (`const`), 5-arg AE overload `linear(t, lo, hi, a, b)` returns 15.
    assert_close(
        eval("linear(0.5, 0, 1, 10, 20)", &ctx, &plus)
            .unwrap()
            .as_f64()
            .unwrap(),
        0.0,
        1e-15,
        "legacy 5-arg linear keeps CM3 3-arg semantics",
    );
    assert_close(
        eval("const t = 0.5; linear(t, 0, 1, 10, 20)", &ctx, &plus)
            .unwrap()
            .as_f64()
            .unwrap(),
        15.0,
        1e-15,
        "extended 5-arg linear uses AE overload",
    );
    assert_close(
        eval("linear(10, 20, 0.25)", &ctx, &plus)
            .unwrap()
            .as_f64()
            .unwrap(),
        12.5,
        1e-15,
        "3-arg linear",
    );

    // CM3 `Cubic.OutIn`: `4 * (t - 0.5)^3 + 0.5`
    for &(t, expected) in &[
        (0.0, 0.0),
        (0.25, 0.4375),
        (0.5, 0.5),
        (0.75, 0.5625),
        (1.0, 1.0),
    ] {
        assert_close(
            eval(&format!("ease({t}, 'Cubic', 'OutIn')"), &ctx, &vanilla)
                .unwrap()
                .as_f64()
                .unwrap(),
            expected,
            1e-15,
            &format!("Cubic.OutIn({t})"),
        );
    }

    // Zoidium `api.js:230` exact `lookAt(from, to)`:
    // `[Math.atan2(-dy, Math.hypot(dx, dz)), Math.atan2(dx, dz), 0]`
    let la_x = eval("lookAt([0, 0, 0], [10, 0, 0])", &ctx, &plus)
        .unwrap()
        .as_f64_vec()
        .unwrap();
    assert_slice_close(&la_x, &[0.0, FRAC_PI_2, 0.0], 1e-15, "lookAt +X");

    let la_yz = eval("lookAt([0, 0, 0], [0, 10, 10])", &ctx, &plus)
        .unwrap()
        .as_f64_vec()
        .unwrap();
    assert_slice_close(&la_yz, &[-FRAC_PI_4, 0.0, 0.0], 1e-15, "lookAt +Y+Z");

    let la_diag = eval("lookAt([1, 2, 3], [2, 3, 4])", &ctx, &plus)
        .unwrap()
        .as_f64_vec()
        .unwrap();
    assert_slice_close(
        &la_diag,
        &[(-1.0_f64).atan2(2.0_f64.sqrt()), FRAC_PI_4, 0.0],
        1e-15,
        "lookAt diagonal",
    );

    let la_back = eval("lookAt([0, 0, 0], [1, 0, -1])", &ctx, &plus)
        .unwrap()
        .as_f64_vec()
        .unwrap();
    assert_slice_close(&la_back, &[0.0, 3.0 * FRAC_PI_4, 0.0], 1e-15, "lookAt back");

    // Degrees <-> radians helpers
    assert_close(
        eval("degreesToRadians(180)", &ctx, &plus)
            .unwrap()
            .as_f64()
            .unwrap(),
        PI,
        1e-15,
        "degreesToRadians(180)",
    );
    assert_close(
        eval("radiansToDegrees(Math.PI)", &ctx, &plus)
            .unwrap()
            .as_f64()
            .unwrap(),
        180.0,
        1e-15,
        "radiansToDegrees(PI)",
    );
}

