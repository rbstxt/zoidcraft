fn assert_close(actual: f64, expected: f64, tol: f64, label: &str) {
    assert!(
        (actual - expected).abs() <= tol,
        "{label}: expected {expected:.15}, got {actual:.15} (diff={:.3e}, tol={tol:.3e})",
        (actual - expected).abs()
    );
}

fn assert_slice_close(actual: &[f64], expected: &[f64], tol: f64, label: &str) {
    assert_eq!(actual.len(), expected.len(), "{label}: length mismatch");
    for (i, (&a, &e)) in actual.iter().zip(expected).enumerate() {
        assert_close(a, e, tol, &format!("{label}[{i}]"));
    }
}

/// Composes a Three.js column-major 4x4 world matrix matching `expresstext-host.cjs` /
/// `expresstext-plus-identity.test.js`:
/// `M_world = T(root_pos) * T(base + ctrl.position) * R_xyz(ctrl.rotation) * S(ctrl.scale)`.
fn compose_anchor_world_matrix(
    root_pos: [f64; 3],
    base: [f64; 3],
    ctrl: &LetterControls,
) -> [f64; 16] {
    let [rx, ry, rz] = ctrl.rotation;
    let (sx, cx) = rx.sin_cos();
    let (sy, cy) = ry.sin_cos();
    let (sz, cz) = rz.sin_cos();

    // Intrinsic XYZ rotation matrix (Three.js Matrix4.makeRotationFromEuler XYZ)
    let r00 = cy * cz;
    let r01 = -cy * sz;
    let r02 = sy;
    let r10 = cx * sz + sx * sy * cz;
    let r11 = cx * cz - sx * sy * sz;
    let r12 = -sx * cy;
    let r20 = sx * sz - cx * sy * cz;
    let r21 = sx * cz + cx * sy * sz;
    let r22 = cx * cy;

    let [scx, scy, scz] = ctrl.scale;
    let tx = root_pos[0] + base[0] + ctrl.position[0];
    let ty = root_pos[1] + base[1] + ctrl.position[1];
    let tz = root_pos[2] + base[2] + ctrl.position[2];

    [
        r00 * scx,
        r10 * scx,
        r20 * scx,
        0.0,
        r01 * scy,
        r11 * scy,
        r21 * scy,
        0.0,
        r02 * scz,
        r12 * scz,
        r22 * scz,
        0.0,
        tx,
        ty,
        tz,
        1.0,
    ]
}

